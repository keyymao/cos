EQB(ROW(X_, D(V("k")), EQ, W(8, ROW(N("3"), V("k"))), PLUS, W(8, ROW(N("4"), V("k"))),
        PLUS, W(8, ROW(N("5"), V("k"))), PLUS, W(8, ROW(N("6"), V("k")))))
