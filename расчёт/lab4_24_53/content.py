#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Содержание отчёта ЛР №4 (вариант 24 / зачётка 53).

Оформление и набор пунктов — по образцу `примеры/лаба3/лаба №3.pdf` (титул, ЦЕЛЬ РАБОТЫ,
ИСХОДНЫЕ ДАННЫЕ, ДОМАШНИЙ РАСЧЁТ, ЭКСПЕРИМЕНТАЛЬНАЯ ЧАСТЬ, ВЫВОД).
Расчёт — по методичке LR_TsOS_4_BIKh_K.pdf, прототип — из ЛР №3
(вариант 24 / зачётка 53).  Картинок из «Спектр-2» нет: оставлены места
для самостоятельно снятых скриншотов.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from mathast import *  # noqa: F401,F403

d = json.loads((HERE / "variant_data_lab4_24_53.json").read_text(encoding="utf-8"))


def ru(x, n=5):
    return f"{x:.{n}f}".replace(".", ",").replace("-", "−")


def sub(b, s):
    return SUB(V(b), L(s))


def zi(power=1):
    return SUP(V("z"), ROW(MINUS, N(str(power))))


def qterm(c0, c1, c2):
    """(c0 + c1 z^-1 + c2 z^-2) со знаками, как в образце."""
    s1 = PLUS if c1 >= 0 else MINUS
    s2 = PLUS if c2 >= 0 else MINUS
    return D(ROW(N(ru(c0)), s1, N(ru(abs(c1))), zi(1), s2, N(ru(abs(c2))), zi(2)))


def frac_z(num, den):
    return FRAC(num, den)


blocks: list[dict] = []


def P(t):
    blocks.append({"type": "p", "text": t})


def PLAIN(t):
    blocks.append({"type": "plain", "text": t})


def H1(t):
    blocks.append({"type": "h1", "text": t})


def EQB(node, stack=True):
    blocks.append({"type": "eq", "math": node, "stack": stack})


def TBL(headers, rows, widths=None):
    blocks.append({"type": "table", "headers": headers, "rows": rows, "widths": widths})


def FIGCAP(t):
    blocks.append({"type": "figcap", "text": t})


def PB():
    blocks.append({"type": "pagebreak"})


# ============================ ТИТУЛ ============================
blocks.append({"type": "title"})

# ============================ ЦЕЛЬ РАБОТЫ ============================
PB()
H1("ЦЕЛЬ РАБОТЫ")
P("Изучение метода билинейного z-преобразования с внесением предыскажений на примере синтеза цифровых ФВЧ Баттерворта и Чебышёва по аналоговым фильтрам прототипам. Моделирование синтезированного цифрового фильтра проводится в среде «Спектр-2».")

# ============================ ИСХОДНЫЕ ДАННЫЕ ============================
PB()
H1("ИСХОДНЫЕ ДАННЫЕ")
PLAIN("N<sub>бр</sub> = 24")
PLAIN("№ зачётки = 53")
PLAIN("F<sub>д</sub> = 14800 Гц")
PLAIN("F<sub>1</sub> = 2220 Гц")
PLAIN("F<sub>3</sub> = 3760 Гц")
PLAIN("a<sub>max</sub> = 0,4455 дБ")
PLAIN("a<sub>min</sub> = 40 дБ")

# ============================ ДОМАШНИЙ РАСЧЁТ ============================
PB()
H1("ДОМАШНИЙ РАСЧЁТ")
P("К цифровому ФНЧ Чебышёва предъявляются требования: F<sub>1</sub> = 2220 Гц, F<sub>3</sub> = 3760 Гц, a<sub>max</sub> = 0,4455 дБ, a<sub>min</sub> = 40 дБ при F<sub>д</sub> = 14800 Гц. Согласно п. 1.2 методических указаний, синтез ведётся по аналоговому ФНЧ-прототипу, уже рассчитанному в лабораторной работе №3 (Чебышёв, n = 6); заново выполняется переход к цифровому фильтру с внесением предыскажений.")
P("Интервал дискретизации T = 1/F<sub>д</sub> = 1/14800 = 0,000067568 с, граничная частота ω<sub>1</sub> = 2πF<sub>1</sub> = 13948,67 рад/с, поэтому ω<sub>1</sub>T/2 = πF<sub>1</sub>/F<sub>д</sub> = π·2220/14800 = 0,47124 и C = ctg(0,47124) = 1,96261, C<super>2</super> = 3,85184.")
P("Преобразование Константинидиса для ФНЧ состоит в подстановке в операторную передаточную функцию выражения:")
EQB(ROW(
    V("p"), EQ, F("ctg"), D(FRAC(ROW(sub("ω", "1"), V("T")), N("2"))), MUL,
    FRAC(ROW(N("1"), MINUS, zi(1)), ROW(N("1"), PLUS, zi(1))),
    EQ, N("1,96261"), MUL,
    FRAC(ROW(N("1"), MINUS, zi(1)), ROW(N("1"), PLUS, zi(1))),
), stack=False)
P("H(p) с домашнего расчёта к лабораторной работе №3:")
EQB(ROW(
    V("H"), D(V("p")), EQ,
    FRAC(
        N("0,09508"),
        ROW(
            D(ROW(SUP(V("p"), N("2")), PLUS, N("0,16050"), V("p"), PLUS, N("1,02917"))),
            D(ROW(SUP(V("p"), N("2")), PLUS, N("0,43850"), V("p"), PLUS, N("0,59614"))),
            D(ROW(SUP(V("p"), N("2")), PLUS, N("0,59900"), V("p"), PLUS, N("0,16313"))),
        ),
    ),
))
P("Проведём замену. После подстановки p = C(1 − z<super>−1</super>)/(1 + z<super>−1</super>) и умножения на (1 + z<super>−1</super>)<super>2</super> каждый квадратичный множитель знаменателя принимает вид c<sub>0</sub> + c<sub>1</sub>z<super>−1</super> + c<sub>2</sub>z<super>−2</super>, где c<sub>0</sub> = C<super>2</super> + aC + b, c<sub>1</sub> = 2(b − C<super>2</super>), c<sub>2</sub> = C<super>2</super> − aC + b; три таких множителя дают в числителе H(z) сомножитель (1 + z<super>−1</super>)<super>6</super>:")
EQB(ROW(
    V("H"), D(V("z")), EQ,
    FRAC(
        ROW(N("0,09508"), SUP(D(ROW(N("1"), PLUS, zi(1))), N("6"))),
        ROW(*[qterm(s["c0"], s["c1"], s["c2"]) for s in d["sections"]]),
    ),
))
PB()
P("Разделив коэффициенты каждого знаменателя на его свободный член (5,19601 · 5,30858 · 5,19057 = 143,17375), получим общий коэффициент усиления K = 0,09508/143,17375 = 0,00066409. Передаточная функция ЦФ в виде произведения передаточных функций биквадратных звеньев:")
EQB(ROW(
    V("H"), D(V("z")), EQ, N("0,00066409"), MUL,
    SUB(V("H"), N("1")), D(V("z")), SUB(V("H"), N("2")), D(V("z")),
    SUB(V("H"), N("3")), D(V("z")),
), stack=False)
for i, s in enumerate(d["sections"], 1):
    EQB(ROW(
        SUB(V("H"), N(str(i))), D(V("z")), EQ,
        FRAC(
            ROW(N("1"), PLUS, N("2"), zi(1), PLUS, zi(2)),
            ROW(N("1"), MINUS if s["a1"] < 0 else PLUS, N(ru(abs(s["a1"]))), zi(1),
                PLUS if s["a2"] >= 0 else MINUS, N(ru(abs(s["a2"]))), zi(2)),
        ),
    ))
TBL(
    ["Звено №", "b<sub>0</sub>", "b<sub>1</sub>", "b<sub>2</sub>", "a<sub>0</sub>", "a<sub>1</sub>", "a<sub>2</sub>"],
    [[str(i), "1", "2", "1", "1", ru(s["a1"]), ru(s["a2"])]
     for i, s in enumerate(d["sections"], 1)],
    widths=[2.4, 1.9, 1.9, 1.9, 1.9, 3.3, 3.3],
)

# ============================ ЭКСПЕРИМЕНТАЛЬНАЯ ЧАСТЬ ============================
PB()
H1("ЭКСПЕРИМЕНТАЛЬНАЯ ЧАСТЬ")
P("На рис. 1 представлена схема ФНЧ Чебышёва и коэффициенты усиления с внесением предыскажений в среде имитационного моделирования РТС «Спектр-2» для значений Варианта №24, полученных в домашнем расчёте. Схема и графики в отчёт не вставляются: моделирование выполняется самостоятельно, места для рисунков оставлены ниже.")
FIGCAP("Рисунок 1 – Схема ФНЧ Чебышёва и её схема с внесением предыскажений")
P("Частота дискретизации системы — 14800 Гц. Три биквадратных звена прямой формы I соединены каскадно; прямые ветви звеньев: b<sub>0</sub> = 1, b<sub>1</sub> = 2, b<sub>2</sub> = 1. Согласно п. 2.1 методических указаний коэффициенты a, кроме a<sub>0</sub>, вводятся в усилители обратной связи с противоположным знаком: −a<sub>1</sub> = 1,08648 / 1,22658 / 1,42131, −a<sub>2</sub> = −0,87875 / −0,67577 / −0,54702. Общий усилитель K = 0,00066409 выносится отдельно. ГТИ: период равен размеру пачки системы, ширина импульса равна 1; для снятия АЧХ добавляется спектроанализатор.")
P("На рис. 2 и рис. 3 представлены графики АЧХ в линейном и логарифмическом масштабе соответственно.")
FIGCAP("Рисунок 2 – График АЧХ в линейном масштабе")
FIGCAP("Рисунок 3 – График АЧХ в логарифмическом масштабе")
P("По расчёту граница полосы пропускания с предыскажением равна 2220 Гц, то есть точно совпадает с техническим заданием (в ЛР №3 без предыскажений она составляла 2074,6 Гц). На заданной границе полосы задержания 3760 Гц ослабление равно 53,35 дБ, а уровня 40 дБ АЧХ достигает уже на частоте около 3261 Гц — требование a ≥ 40 дБ выполняется с запасом.")

# ============================ ВЫВОД ============================
PB()
H1("ВЫВОД")
P("В ходе данной лабораторной работы освоен метод билинейного z-преобразования с внесением предыскажений для синтеза цифровых БИХ-фильтров: для варианта 24 (зачётка 53) рассчитан ФНЧ Чебышёва шестого порядка с константой преобразования C = 1,96261 и получены все необходимые данные для моделирования фильтра в среде «Спектр-2».")
