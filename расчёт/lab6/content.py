def ru(value, digits=8):
    if math.isinf(value):
        return "∞"
    return f"{value:.{digits}f}".replace(".", ",").replace("-", "−")


def sub(base, index):
    return SUB(V(base), L(index))


def zinv(power=1):
    return SUP(V("z"), ROW(MINUS, N(str(power))))


