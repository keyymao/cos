#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Содержание отчёта ЛР №6 (вариант 24 / зачётка 53).

Оформление и набор пунктов — по образцу `лабораторные/лаба4/…(вариант 24, зачётка 53).pdf`
и `примеры/лаба4/лаба №4.pdf`: титул, ЦЕЛЬ РАБОТЫ, ИСХОДНЫЕ ДАННЫЕ,
ДОМАШНИЙ РАСЧЁТ, ЭКСПЕРИМЕНТАЛЬНАЯ ЧАСТЬ, ВЫВОД. Лишних разделов нет.
Расчёт — по методичке LR_TsOS_6_KIKh_KAJZER.pdf (ФНЧ, окно Кайзера).
Скриншоты «Спектр-2» не рисуются: оставлены места под них.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from mathast import *  # noqa: F401,F403

d = json.loads((HERE / "variant_data_lab6_24_53.json").read_text(encoding="utf-8"))


def ru(x, n=8):
    return f"{x:.{n}f}".replace(".", ",").replace("-", "−")


def sub(b, s):
    return SUB(V(b), L(s))


def zi(power=1):
    return SUP(V("z"), ROW(MINUS, N(str(power))))


Fd_ = sub("F", "д")
F1_ = sub("F", "1")
F3_ = sub("F", "3")
hu_ = sub("h", "u")
amin_ = sub("a", "min")
d2_ = sub("δ", "2")

blocks: list[dict] = []


def P(t):
    blocks.append({"type": "p", "text": t})


def PLAIN(t):
    blocks.append({"type": "plain", "text": t})


def H1(t):
    blocks.append({"type": "h1", "text": t})


def EQB(node, stack=True):
    blocks.append({"type": "eq", "math": node, "stack": stack})


def TBL(caption, headers, rows, widths=None):
    blocks.append({"type": "table", "caption": caption, "headers": headers, "rows": rows, "widths": widths})


def FIG(filename, caption=None, width=15.6):
    blocks.append({"type": "figure", "path": str(HERE / "assets" / filename), "caption": caption, "width": width})


def FIGCAP(caption):
    blocks.append({"type": "figcap", "text": caption})


def PB():
    blocks.append({"type": "pagebreak"})


# ============================ ТИТУЛ ============================
blocks.append({"type": "title"})

# ============================ ЦЕЛЬ РАБОТЫ ============================
PB()
H1("ЦЕЛЬ РАБОТЫ")
P("Изучение метода окон на примере синтеза цифрового ФНЧ с применением окна Кайзера. Моделирование синтезированного цифрового фильтра проводится в среде «Спектр-2».")

# ============================ ИСХОДНЫЕ ДАННЫЕ ============================
PB()
H1("ИСХОДНЫЕ ДАННЫЕ")
PLAIN("N<sub>бр</sub> = 24")
PLAIN("№ зачётки = 53")
PLAIN("F<sub>д</sub> = 11200 Гц")
PLAIN("F<sub>1</sub> = 1305 Гц")
PLAIN("F<sub>3</sub> = 2940 Гц")
PLAIN("δ<sub>1</sub> = 0,05")
PLAIN("δ<sub>2</sub> = 0,01")

# ============================ ДОМАШНИЙ РАСЧЁТ ============================
PB()
H1("ДОМАШНИЙ РАСЧЁТ")
P("К цифровому ФНЧ предъявляются требования: F<sub>1</sub> = 1305 Гц, F<sub>3</sub> = 2940 Гц, δ<sub>1</sub> = 0,05, δ<sub>2</sub> = 0,01 при F<sub>д</sub> = 11200 Гц. Требования заданы в таблице 1 методических указаний через номер варианта: F<sub>д</sub> = 10000 + 50·N<sub>бр</sub>, F<sub>1</sub> = 705 + 25·N<sub>бр</sub>, F<sub>3</sub> = 2100 + 35·N<sub>бр</sub>.")
P("Нормированная частота среза (частота разрыва идеальной АЧХ) выбирается посередине переходной полосы:")
EQB(ROW(
    SUB(V("f"), V("c")), EQ,
    FRAC(ROW(F1_, PLUS, F3_), ROW(N("2"), Fd_)), EQ,
    FRAC(ROW(N("1305"), PLUS, N("2940")), ROW(N("2"), MUL, N("11200"))),
    EQ, N(ru(d["fc"], 6)),
))
P("Отсчёты импульсной характеристики «идеального» ФНЧ вычисляются по формуле (2) методических указаний:")
EQB(ROW(
    hu_, D(V("n")), EQ,
    FRAC(ROW(F("sin"), D(ROW(N("2"), V("π"), SUB(V("f"), V("c")), V("n")))), ROW(V("π"), V("n"))),
))
P("Для нулевого отсчёта раскрывается неопределённость:")
EQB(ROW(hu_, D(N("0")), EQ, N("2"), SUB(V("f"), V("c")), EQ,
        N("2"), MUL, N(ru(d["fc"], 6)), EQ, N(ru(d["coefficients"][8]["h_ideal"], 6))), stack=False)
P("Нормированная ширина переходной полосы и минимально допустимое подавление в полосе задержания:")
EQB(ROW(V("Δ"), V("F"), EQ, FRAC(ROW(F3_, MINUS, F1_), Fd_), EQ,
        FRAC(ROW(N("2940"), MINUS, N("1305")), N("11200")), EQ, N(ru(d["delta_F"], 6))))
EQB(ROW(amin_, EQ, MINUS, N("20"), F("lg"), D(d2_), EQ,
        MINUS, N("20"), F("lg"), D(N("0,01")), EQ, N("40"), L(" дБ")))
P("Постоянная D и оценка порядка фильтра R по формулам (5)–(7) методических указаний:")
EQB(ROW(V("D"), EQ, FRAC(ROW(amin_, MINUS, N("7,95")), N("14,36")), EQ,
        FRAC(ROW(N("40"), MINUS, N("7,95")), N("14,36")), EQ, N(ru(d["D"], 6))))
EQB(ROW(V("R"), EQ, D(ROW(FRAC(V("D"), ROW(V("Δ"), V("F"))), PLUS, N("1")), "[", "]"), EQ,
        D(N(ru(d["R_exact"], 6)), "[", "]"), EQ, N(str(d["R"]))))
P("Порядок получился чётным: R = 16, длина ИХ N = R + 1 = 17 (нечётная). Такой фильтр относится к КИХ-фильтрам I типа с симметричной ИХ и строго линейной ФЧХ, поэтому для ФНЧ он пригоден.")
P("Параметр β окна Кайзера при 21 ≤ a<sub>min</sub> ≤ 50 дБ определяется по формуле (9):")
EQB(ROW(V("β"), EQ,
        N("0,5842"), SUP(D(ROW(amin_, MINUS, N("21"))), N("0,4")), PLUS,
        N("0,07886"), D(ROW(amin_, MINUS, N("21"))), EQ, N(ru(d["beta"], 6))))
P("Отсчёты оконной функции для −8 ≤ n ≤ 8 вычисляются по формуле (8):")
window_ratio = FRAC(ROW(N("2"), V("n")), ROW(V("N"), MINUS, N("1")))
EQB(ROW(V("w"), D(V("n")), EQ,
        FRAC(
            ROW(SUB(V("I"), N("0")), D(ROW(V("β"), SQRT(ROW(N("1"), MINUS, SUP(D(window_ratio), N("2"))))))),
            ROW(SUB(V("I"), N("0")), D(V("β"))),
        )))
P("Здесь I<sub>0</sub>(x) — модифицированная функция Бесселя первого рода нулевого порядка. В центре окна w(0) = 1, значения симметричны относительно нуля.")
P("Импульсная характеристика реального фильтра получается умножением отсчётов идеальной ИХ на окно:")
EQB(ROW(V("h"), D(V("n")), EQ, hu_, D(V("n")), MUL, V("w"), D(V("n"))), stack=False)
P("Результаты расчёта сведены в таблицу 1. Коэффициенты b(i) каузальной реализации получены сдвигом центрированной ИХ на восемь отсчётов: b(i) = h(n), n = i − 8.")
rows = []
for row in d["coefficients"]:
    rows.append([
        f"b({row['i']})", str(row["n"]).replace("-", "−"), ru(row["h_ideal"], 6),
        ru(row["w"], 6), ru(row["h"], 6),
    ])
TBL(
    "Таблица 1 – Рассчитанные отсчёты ИХ",
    ["b(i)", "n", "h<sub>u</sub>(n)", "w(n)", "h(n)"],
    rows,
    widths=[2.6, 1.3, 4.3, 3.9, 4.3],
)
P("Коэффициенты симметричны: b(0) = b(16), b(1) = b(15) и так далее, центральный b(8) = 0,379018 — максимальный. Поэтому фильтр имеет линейную ФЧХ, а групповая задержка постоянна и равна R/2 = 8 отсчётам.")
P("Графики ИХ «идеального» фильтра, оконной функции и ИХ реального спроектированного фильтра приведены ниже.")
FIG("fig1_ideal_ih.png", width=13.2)
FIG("fig2_kaiser_window.png", width=13.2)
FIG("fig3_real_ih.png", width=13.2)

# ============================ ЭКСПЕРИМЕНТАЛЬНАЯ ЧАСТЬ ============================
PB()
H1("ЭКСПЕРИМЕНТАЛЬНАЯ ЧАСТЬ")
P("На рис. 1 представлена схема цифрового ФНЧ в среде имитационного моделирования РТС «Спектр-2» для значений Варианта №24, полученных в домашнем расчёте. Схема и графики в отчёт не вставляются: моделирование выполняется самостоятельно, места для рисунков оставлены ниже.")
FIGCAP("Рисунок 1 – Схема цифрового ФНЧ")
P("Частота дискретизации системы — 11200 Гц. Шестнадцать линий задержки соединены последовательно; к входу и выходам линий задержки подключены 17 усилителей с коэффициентами b(0)…b(16) из таблицы 1, их выходы подаются на сумматор на 17 входов. Коэффициенты вводятся со своими знаками, отдельный общий множитель не требуется. ГТИ: период равен размеру пачки системы, ширина импульса равна 1; для снятия АЧХ добавляется спектроанализатор.")
P("На рис. 2 и рис. 3 представлены ИХ и АЧХ цифрового фильтра соответственно.")
FIGCAP("Рисунок 2 – ИХ цифрового ФНЧ")
FIGCAP("Рисунок 3 – АЧХ цифрового ФНЧ")
check = d["check"]
P(f"По расчёту в полосе пропускания 0…1305 Гц АЧХ лежит в пределах {ru(check['pass_min'], 6)}…{ru(check['pass_max'], 6)}, то есть внутри допуска 0,95…1,05. В полосе задержания 2940…5600 Гц максимальный уровень АЧХ равен {ru(check['stop_max'], 6)}, что не превышает δ<sub>2</sub> = 0,01, а на границе полосы задержания 2940 Гц ослабление составляет {ru(d['points'][3]['attenuation_db'], 3)} дБ. Уровень 40 дБ достигается уже на частоте около {d['attenuation_40db_frequency']:.0f} Гц, поэтому требование a<sub>min</sub> ≥ 40 дБ выполняется с запасом.")

# ============================ ВЫВОД ============================
PB()
H1("ВЫВОД")
P(f"В ходе лабораторной работы был изучен метод окон синтеза цифровых КИХ-фильтров и выполнено проектирование цифрового ФНЧ с использованием окна Кайзера для варианта 24 (зачётка 53): F<sub>д</sub> = 11200 Гц, F<sub>1</sub> = 1305 Гц, F<sub>3</sub> = 2940 Гц, F<sub>c</sub> = 2122,5 Гц, β = {ru(d['beta'], 6)}, R = 16, N = 17. Полученная АЧХ удовлетворяет заданным требованиям по обоим допускам, а коэффициенты b(0)…b(16) и контрольные точки подготовлены для моделирования фильтра в среде «Спектр-2».")
