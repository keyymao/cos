# ============================== задание 10 =================================
rep.h1("Задание 10. Формулы для расчёта АЧХ и ФЧХ в произвольной точке")
rep.p("Частотная характеристика получается подстановкой z = e<super>jωT</super> = "
      "e<super>jω̄</super>, где ω̄ = ωT — нормированная частота:")
rep.eq(ROW(V("H"), PAR(SUP(V("e"), ROW(V("j"), V("ω̄")))), O("="),
           FRAC(ROW(SUB(V("b"), N("0")), PLUS, SUB(V("b"), N("1")),
                    SUP(V("e"), ROW(MINUS, V("j"), V("ω̄"))), PLUS,
                    SUB(V("b"), N("2")), SUP(V("e"), ROW(MINUS, V("j"), N("2"), V("ω̄")))),
                ROW(N("1"), PLUS, SUB(V("a"), N("1")),
                    SUP(V("e"), ROW(MINUS, V("j"), V("ω̄"))), PLUS,
                    SUB(V("a"), N("2")), SUP(V("e"), ROW(MINUS, V("j"), N("2"), V("ω̄")))))))
rep.p("По формуле Эйлера e<super>−jkω̄</super> = cos(kω̄) − j·sin(kω̄) выделяем вещественные и "
      "мнимые части числителя и знаменателя:")
rep.eq(ROW(F("Re"), L("ч"), O("="), SUB(V("b"), N("0")), PLUS, SUB(V("b"), N("1")), F("cos"),
           V("ω̄"), PLUS, SUB(V("b"), N("2")), F("cos"), N("2"), V("ω̄")))
rep.eq(ROW(F("Im"), L("ч"), O("="), MINUS, SUB(V("b"), N("1")), F("sin"), V("ω̄"),
           MINUS, SUB(V("b"), N("2")), F("sin"), N("2"), V("ω̄")))
rep.eq(ROW(F("Re"), L("з"), O("="), N("1"), PLUS, SUB(V("a"), N("1")), F("cos"), V("ω̄"),
           PLUS, SUB(V("a"), N("2")), F("cos"), N("2"), V("ω̄")))
rep.eq(ROW(F("Im"), L("з"), O("="), MINUS, SUB(V("a"), N("1")), F("sin"), V("ω̄"),
           MINUS, SUB(V("a"), N("2")), F("sin"), N("2"), V("ω̄")))
rep.p("АЧХ — модуль частотной характеристики, ФЧХ — её аргумент (арктангенс берётся с учётом "
      "квадранта, то есть через atan2):")
rep.eq(ROW(V("A"), PAR(ROW(V("ω̄"))), O("="),
           FRAC(SQRT(ROW(SUP(SUB(F("Re"), L("ч")), N("2")), PLUS,
                        SUP(SUB(F("Im"), L("ч")), N("2")))),
                SQRT(ROW(SUP(SUB(F("Re"), L("з")), N("2")), PLUS,
                        SUP(SUB(F("Im"), L("з")), N("2")))))))
rep.eq(ROW(V("φ"), PAR(ROW(V("ω̄"))), O("="), F("arctg"),
           PAR(FRAC(SUB(F("Im"), L("ч")), SUB(F("Re"), L("ч")))), MINUS, F("arctg"),
           PAR(FRAC(SUB(F("Im"), L("з")), SUB(F("Re"), L("з"))))))
rep.p("После подстановки коэффициентов варианта 10:")
rep.eq_text("A(ω̄) = √[(1 − 0,7234·cos ω̄ + 0,4231·cos 2ω̄)² + (0,7234·sin ω̄ − 0,4231·sin 2ω̄)²] / "
            "√[(1 + 0,7234·cos ω̄ + 0,9234·cos 2ω̄)² + (0,7234·sin ω̄ + 0,9234·sin 2ω̄)²]")
rep.eq_text("φ(ω̄) = arctg[(0,7234·sin ω̄ − 0,4231·sin 2ω̄) / (1 − 0,7234·cos ω̄ + 0,4231·cos 2ω̄)] "
            "− arctg[−(0,7234·sin ω̄ + 0,9234·sin 2ω̄) / (1 + 0,7234·cos ω̄ + 0,9234·cos 2ω̄)]")
rep.p("АЧХ — чётная функция, ФЧХ — нечётная, обе периодичны с периодом 2π, поэтому достаточно "
      "рассматривать диапазон 0 ≤ ω̄ ≤ π. Полюсы лежат внутри единичной окружности "
      f"(r = {num(RAD)} &lt; 1), значит, знаменатель в ноль не обращается и разрывов нет.")

