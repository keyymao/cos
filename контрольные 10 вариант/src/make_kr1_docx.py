def num(x: float, d: int = 4) -> str:
    """Русская запись числа: «−0,7234»."""
    s = f"{x:.{d}f}"
    if s.startswith("-"):
        s = "−" + s[1:]
    return s.replace(".", ",")


def sgn(x: float, d: int = 4) -> str:
    """Слагаемое со знаком: « + 0,5123» / « − 0,7234»."""
    s = num(x, d)
    return (" + " + s[1:]) if s.startswith("−") else (" + " + s)


