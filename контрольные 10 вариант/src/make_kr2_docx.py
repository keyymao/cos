def num(x: float, d: int = 2) -> str:
    s = f"{x:.{d}f}"
    if s.startswith("-"):
        s = "−" + s[1:]
    return s.replace(".", ",")


def snippet(*names: str) -> str:
    """Полный текст функций name из kr2_signal_system.py (для вставки в текст)."""
    src = SRC.read_text(encoding="utf-8")
    parts = []
    for name in names:
        m = re.search(rf"^def {name}\b.*?(?=^[^ \t\n]|\Z)", src, re.S | re.M)
        assert m, name
        parts.append(m.group(0).rstrip())
    return "\n\n\n".join(parts)


def listing(path: Path) -> str:
    """Листинг файла без фрагментов между маркерами «# >>>plots» / «# <<<plots»."""
    out, skip = [], False
    for ln in path.read_text(encoding="utf-8").splitlines():
        s = ln.strip()
        if s.startswith("# >>>plots"):
            skip = True
            continue
        if s.startswith("# <<<plots"):
            skip = False
            continue
        if not skip:
            out.append(ln.rstrip())
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


