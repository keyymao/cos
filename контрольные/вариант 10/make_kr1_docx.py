b0, b1, b2 = 1.0, -0.7234, -0.4231
a1, a2 = 0.7234, 0.9234
b = [b0, b1, b2]
a = [1.0, a1, a2]

poles = np.roots(a)
zeros = np.roots(b)
p = poles[0]
r = float(abs(p))
phi = float(np.angle(p))
sin_phi = float(np.sin(phi))
Dp = a1**2 - 4 * a2          # дискриминант знаменателя
Dz = b1**2 - 4 * b0 * b2     # дискриминант числителя
z1, z2 = float(zeros[0].real), float(zeros[1].real)


def h_formula(n):
    v = b0 * r**n * np.sin((n + 1) * phi) / sin_phi
    if n >= 1:
        v += b1 * r**(n - 1) * np.sin(n * phi) / sin_phi
    if n >= 2:
        v += b2 * r**(n - 2) * np.sin((n - 1) * phi) / sin_phi
    return v


def h_terms(n):
    """Слагаемые формулы ИХ для n (для таблицы задания 5)."""
    t1 = b0 * r**n * np.sin((n + 1) * phi) / sin_phi
    t2 = b1 * r**(n - 1) * np.sin(n * phi) / sin_phi if n >= 1 else 0.0
    t3 = b2 * r**(n - 2) * np.sin((n - 1) * phi) / sin_phi if n >= 2 else 0.0
    return t1, t2, t3


def h_de(n):
    if n == 0:
        return b0
    if n == 1:
        return b1 - a1 * h_de(0)
    return b2 - a1 * h_de(n - 1) - a2 * h_de(n - 2)


def Hjw(w):
    z = np.exp(1j * w)
    return (b0 + b1 / z + b2 / z**2) / (1 + a1 / z + a2 / z**2)


pts = [("ω̄ = 0", 0.0), ("ω̄ = π/4", np.pi / 4), ("ω̄ = π/2", np.pi / 2),
       ("ω̄ = φₚ", phi), ("ω̄ = π", np.pi)]
